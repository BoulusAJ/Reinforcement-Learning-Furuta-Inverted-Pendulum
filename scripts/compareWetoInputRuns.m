function value = getNumericValue(T, name)
if ~ismember(name, T.Properties.VariableNames)
    value = NaN;
    return;
end

x = T.(name);
if isempty(x)
    value = NaN;
elseif isnumeric(x) || islogical(x)
    value = double(x(1));
else
    value = str2double(string(x(1)));
end
end

function value = getStringValue(T, name, fallback)
if ~ismember(name, T.Properties.VariableNames)
    value = string(fallback);
    return;
end

x = T.(name);
if isempty(x)
    value = string(fallback);
else
    value = string(x(1));
end
end

function base = getFileBase(path)
[~, base] = fileparts(path);
base = string(base);
end
